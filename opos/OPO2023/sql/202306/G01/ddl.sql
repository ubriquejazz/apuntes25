-- Crear una base de datos 
DROP DATABASE IF EXISTS LABORATORIO;
CREATE DATABASE LABORATORIO CHARACTER SET utf8mb4;
USE LABORATORIO;

-- Crear un usuario US_LAB con password
CREATE USER us_lab@localhost 
    IDENTIFIED BY 'password';

-- Asignar derechos totales sobre la base de datos LABORATORIO
GRANT SELECT,INSERT,UPDATE,DELETE,CREATE,DROP 
    ON LABORATORIO.*
    TO us_lab@localhost;

-- Conectarse con el usuario US_LAB a la base de datos LABORATORIO
mysql -u us_lab -p

-- Crear las tablas  en el orden correcto con las siguientes restricciones:
CREATE TABLE PACIENTES (
    DNI_PAC CHAR(10) PRIMARY KEY,
    NOMBRE_PAC VARCHAR(50) NOT NULL,
    TELEFONO VARCHAR(20) NOT NULL,
    ASEGURADORA VARCHAR(50));

CREATE TABLE ESPECIALIDADES (
    ID_ESP INT(10) PRIMARY KEY,
    DESC_ESP VARCHAR(50));

CREATE TABLE DOCTORES (
    DNI_DOC CHAR(10) PRIMARY KEY,
    NOMBRE_DOC VARCHAR(50) NOT NULL,
    ESPECIALIDAD INT(10),
    TELEFONO VARCHAR(20) NOT NULL,
    CONSTRAINT FK_DTOR_ESP FOREIGN KEY (ESPECIALIDAD) REFERENCES ESPECIALIDADES(ID_ESP)
    );

CREATE TABLE TIPOS_ANALISIS (
    ID_ANA INT(10) PRIMARY KEY,
    DESC_ANA VARCHAR(100));

CREATE TABLE PETICIONES (
    ID_PET INT(10),
    FECHA_PET VARCHAR(50),
    ID_ANA INT(10),
    DNI_PAC CHAR(10),
    DNI_DOC CHAR(10),
    CONSTRAINT FK_PET_ANAL FOREIGN KEY (ID_ANA) REFERENCES TIPOS_ANALISIS(ID_ANA),
    CONSTRAINT FK_PET_PAC FOREIGN KEY (DNI_PAC) REFERENCES PACIENTES(DNI_PAC),
    CONSTRAINT FK_PET_DTOR FOREIGN KEY (DNI_DOC) REFERENCES DOCTORES(DNI_DOC),
    CONSTRAINT PK_PETICION PRIMARY KEY (ID_PET, ID_ANA, DNI_PAC, DNI_DOC)
);

