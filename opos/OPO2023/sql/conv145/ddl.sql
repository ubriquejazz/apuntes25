-- Crear una base de datos 
DROP DATABASE IF EXISTS conv145;
CREATE DATABASE conv145 CHARACTER SET utf8mb4;
USE conv145;

CREATE TABLE CLIENTES (
    DNI_CLIENTE CHAR(9) PRIMARY KEY,
    NOM_CLIENTE VARCHAR(100),
    TEL_CLIENTE CHAR(9),
    DOM_CLIENTE VARCHAR(100)
) ENGINE=InnoDB;

CREATE TABLE ANIMALES (
    ID_ANIMAL CHAR(10) PRIMARY KEY,
    DNI_CLIENTE CHAR(9),
    NOMBRE VARCHAR(100),
--   ESPECIE VARCHAR(100),
    RAZA VARCHAR(100)
) ENGINE=InnoDB;

ALTER TABLE ANIMALES ADD CONSTRAINT FK_ANIMALES 
    FOREIGN KEY (DNI_CLIENTE) REFERENCES CLIENTES(DNI_CLIENTE);
 
CREATE TABLE VISITAS (
    ID_VISITA CHAR(10) PRIMARY KEY,
    ID_ANIMAL CHAR(10),
    FECHA DATE,
    PRECIO INT(10)
) ENGINE=InnoDB;

ALTER TABLE VISITAS ADD CONSTRAINT FK_VISITAS_ANIMALES 
    FOREIGN KEY (ID_ANIMAL) REFERENCES ANIMALES(ID_ANIMAL);
 
CREATE TABLE PRUEBAS (
    ID_PRUEBA CHAR(10) PRIMARY KEY,
    TIPO_PRUEBA VARCHAR(20),
    ID_VISITA CHAR(10),
    INFORME VARCHAR(200),
    FECHA DATE
) ENGINE=InnoDB;

ALTER TABLE PRUEBAS ADD CONSTRAINT FK_PRUEBAS_VISITAS
    FOREIGN KEY (ID_VISITA) REFERENCES VISITAS(ID_VISITA);
